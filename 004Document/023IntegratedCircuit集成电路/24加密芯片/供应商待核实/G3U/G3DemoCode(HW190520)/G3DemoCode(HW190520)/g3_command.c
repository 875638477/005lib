/**
  * @brief  Generates a signature using input data and target key... 
  *  Note:
  *     The signature algorithm is determined as the target key type.
  *  Parameters (0x86)
  *      key_index                       : Key sector index(p1) 
  *      sign_option                 : Signature algorithm.(p2) It can be one of the following values : 
  *                                         SIGN_ECDSA_EXT_SHA256,SIGN_ECDSA_WITH_SHA256 - The target key type must be ECC_PUF or ECC_PRV 
  *                                         SIGN_HMAC - The target key type must be SHA256 
  *                                         SIGN_SYMM, SIGN_SESSION_SYMM - The target key type must be AES128 or SM4 
  *      msg                          :  Input data to be used for generating a signature 
  *      msg_size                   :TThe size of msg 
  *      sign_structure                        :Command outputs. It can be one of the following structures : 
  *                                         ST_SIGN_ECDSA : r[32] || s[32] 
  *                                         ST_SIGN_SYMM : sign[16] 
  *                                         ST_SIGN_HMAC : sign[32]  
  *      structure_size                   : The size of sign_structure   
  *  Returns
  *      G3_StatusTypeDef
  */

G3_StatusTypeDef g3api_sign(uint8_t key_index, EN_SIGN_OPTION sign_option, uint8_t * msg, uint8_t msg_size, void * sign_structure, uint8_t structure_size)
{    
      PRINTF("\r\n######################g3api_sign######################\r\n");
        switch (sign_option)
	{
	case SIGN_ECDSA_EXT_SHA256:
        //case SIGN_SM2sign_EXT_SM3:  
	case SIGN_ECDSA_WITH_SHA256:
        //case SIGN_SM2sign_WITH_SM3:
		if (structure_size != 64){
			return G3_INVALID_SIZE;
		}
		break;
	case SIGN_HMAC:
		if (structure_size != 32){
			return G3_INVALID_SIZE;
		}
		break;
	case SIGN_SYMM:
	case SIGN_SESSION_SYMM:
		if (structure_size != 16){
			return G3_INVALID_SIZE;
		}
		break;
	default:
		return G3_INVALID_SIZE;
		break;
	}
  

    return g3_normal_process(G3_SIGN, key_index, sign_option,msg, msg_size,&sign_structure);   
}


/**
  * @brief  Verifies the signature... 
  *  Note:
  *     The target sector should be a public key or symmetric key To obtain AC, use the dynamic_auth.
  *  Parameters (0x87)
  *      key_index                       : Key sector index(p1) 
  *      verify_option                    : The option of command(p2) It can be one of the following values : 
  *                                         VERYFY_ECDSA_EXT_SHA256,VERIFY_SM2sign_EXT_SM2,VERYFY_ECDSA_WITH_SHA256,VERIFY_SM2sign_WITH_SM3,VERYFY_HMAC,VERYFY_SYMM,VERIFY_SESSION_SYMM, VERYFY_EXT_PUB_ECDSA_EXT_SHA256,VERYFY_EXT_PUB_ECDSA_WITH_SHA256 
  *      msg                             :Input data, it contains data and signature 
  *      msg_size                        :The size of input data 
  *      sign_structure                  : Command outputs. It can be one of the following structures : 
  *                                         ST_SIGN_ECDSA : r[32] || s[32]  
  *                                         ST_SIGN_SYMM : sign[16]   
  *                                         ST_SIGN_HMAC : sign[32]                        
  *      structure_size                  : The size of sign_sturucture
  *  Returns
  *      G3_StatusTypeDef
  */

G3_StatusTypeDef g3api_verify(uint8_t key_index, EN_VERIFY_OPTION verify_option, uint8_t * msg, uint8_t msg_size, void * sign_structure, uint8_t structure_size)
{
  G3_StatusTypeDef ret_code;
  uint8_t * pbuff = (uint8_t *)malloc(msg_size + structure_size);
  
         
   PRINTF("\r\n######################g3api_verify######################\r\n");   
	switch (verify_option)
	{
	case VERIFY_ECDSA_EXT_SHA256:
        //case VERIFY_SM2sign_EXT_SM3:
	case VERIFY_ECDSA_WITH_SHA256:
        //case VERIFY_SM2sign_WITH_SM3:  
	case VERIFY_EXT_PUB_ECDSA_EXT_SHA256:
	case VERIFY_EXT_PUB_ECDSA_WITH_SHA256:
		if (structure_size != 64){
			return G3_INVALID_SIZE;
		}

		break;
	case VERIFY_HMAC:
		if (structure_size != 32){
			return G3_INVALID_SIZE;
		}
		break;
	case VERIFY_SYMM:
	case VERIFY_SESSION_SYMM:
		if (structure_size != 16){
			return G3_INVALID_SIZE;
		}
		break;
		break;
	default:
		return G3_INVALID_SIZE;
		break;
	}

   
   	memcpy(pbuff, msg, msg_size);
	memcpy(pbuff + msg_size, sign_structure, structure_size);
                
	ret_code = g3_normal_process(G3_VERIFY,  key_index, verify_option, pbuff, msg_size + structure_size,NULL);

    	free(pbuff);
        
        return ret_code;
  
}

