/**
  * @brief  Verifies a certificate, and then update a public key or store it in public key of temporary memory The session can be generated by the public key of temporary memory. 
  *  Parameters (0x8D)
  *      key_index                       : Key sector index(p1) 
  *      certification_write_mode        : The mode of certificate write It can be one of the following values : 
  *                                        TO_TEMP
  *                                        TO_KEY_SECTOR 
  *      cert                            : Input a certificate to verify 
  *      cert_size                       : The size of certificate
  *  Returns
  *      G3_StatusTypeDef
  */
G3_StatusTypeDef g3api_certification(uint8_t key_index, EN_CERTIFICATION_WRITE_MODE certification_write_mode, uint8_t * cert, int16_t cert_size)
{
  G3_StatusTypeDef ret_code;
  int16_t unit_size=240;
  int16_t remain_size = cert_size;
  uint8_t * psubcert = cert;
  
  uint8_t index = 0; 
	
  if (remain_size >1024 )
      return G3_INVALID_SIZE;
  
   PRINTF("\r\n######################g3api_certification######################\r\n");
   
   	while (remain_size>0)
	{
          	uint16_t realsize = min(remain_size, unit_size);
		if (remain_size <= unit_size)
		{
			index = 0xff;
		}
                
		ret_code = g3_normal_process(G3_CERT, key_index, MAKEWORD(index, certification_write_mode), psubcert, realsize,NULL);
       
                if(ret_code!= G3_OK)
                    return ret_code;
                              
		psubcert += unit_size;
		remain_size -= unit_size;
		
		index++;
	} 
   
          return ret_code;
}


