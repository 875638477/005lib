/**
  * @brief  Issues a certificate and store it. Add the pair public key of private key in target sector to certificate The length of the certificate cannot exceed 1024 bytes... 
  *  Parameters (0x8E)
  *      key_index                       : Key sector index(p1) 
  *      public_key_pos                  : The public key position 
  *      issue_cert_area_type            : The area type of the sector to store the issued certificate It can be one of the following values : 
  *                                         ISCRT_KEY_AREA   
  *                                         ISCRT_DATA_AREA_0 
  *                                         ISCRT_DATA_AREA_1  
  *      sector_num_to_store             :The sector number to store the issued certificate 
  *      key_id                          :Factory key ID or the sector number of private key 
  *      encrypted_key                   : When using key_id as a factory key id, encrypted_key must be given                       
  *      cert                            : Input TBS certificate 
  *      cert_size                       : The size of tbs certificate
  *  Returns
  *      G3_StatusTypeDef
  */

G3_StatusTypeDef g3api_issue_certification(uint8_t key_index, uint16_t public_key_pos, EN_ISSUE_CERT_AREA_TYPE issue_cert_area_type, uint8_t sector_num_to_store, uint16_t key_id, uint8_t* encrypted_key, uint8_t * cert, uint16_t cert_size)
{
  G3_StatusTypeDef ret_code;
  int16_t unit_size=240;
  int16_t remain_size = cert_size;
  uint8_t * psubcert = cert;
  uint8_t buff[64];
        
  uint8_t index = 0; 
	
  if (remain_size >935 )
      return G3_INVALID_SIZE;
  
     PRINTF("\r\n######################g3api_issue_certification######################\r\n");
	while (remain_size>0)
	{
		uint16_t realsize = min(remain_size, unit_size);

		uint8_t unit_pub_pos = -1;
		if (public_key_pos < unit_size && public_key_pos>=0) unit_pub_pos = public_key_pos;
		ret_code = g3_normal_process(G3_ISSUE_CERT, key_index, MAKEWORD(index, unit_pub_pos), psubcert, realsize,NULL);
       
                if(ret_code!= G3_OK)
                    return ret_code;
                
		psubcert += unit_size;
		remain_size -= unit_size;
		public_key_pos -= unit_size;

		index++;
	};

	index = 0xff;
	buff[0] = issue_cert_area_type;
	buff[1] = sector_num_to_store;
        buff[2] = key_id >> 8;
	buff[3] = key_id;
        
	if (encrypted_key)
	{
		memcpy(&buff[4], encrypted_key, 32);
		ret_code = g3_normal_process(G3_ISSUE_CERT, key_index, 0XFFFF, buff, 4+32,NULL);
	}
	else
	{
		ret_code = g3_normal_process(G3_ISSUE_CERT, key_index, 0XFFFF, buff, 4,NULL);
	}

	return ret_code;      
  
}



