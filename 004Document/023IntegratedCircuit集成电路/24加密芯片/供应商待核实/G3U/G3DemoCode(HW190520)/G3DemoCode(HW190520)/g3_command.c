/**
  * @brief  Verifies the signature and obtain AC... 
  *  Note:
  *     Input signature must be generated using challenge that generated in G3
  *  Parameters (0x87)
  *      key_index                       : Key sector index(p1) 
  *      dauth_option                    : The mode of the command(p2_lower) It can be one of the following values :   
  *                                         DYN_AUTH_ECDSA_SHA256, DYN_AUTH_HMAC, DYN_AUTH_SYMM, DYN_AUTH_CERT_PUB_ECDSA_SHA256  
  *      pos_pub_dynamic                 : A random position(p2_upper)   
  *      msg                             :Input data, it contains data and signature 
  *      msg_size                        :The size of input data 
  *      sign_structure                  : Command outputs. It can be one of the following structures : 
  *                                         ST_SIGN_ECDSA : r[32] || s[32]  
  *                                         ST_SIGN_SYMM : sign[16]   
  *                                         ST_SIGN_HMAC : sign[32]                        
  *      structure_size                  : The size of sign_sturucture
  *  Returns
  *      G3_StatusTypeDef
  */

G3_StatusTypeDef g3api_dynamic_auth(uint8_t key_index, EN_DYNAMIC_AUTH dauth_option, uint8_t pos_pub_dynamic, uint8_t * msg, uint8_t msg_size, void * sign_structure, uint8_t structure_size)
{
  G3_StatusTypeDef ret_code;
  uint8_t * pbuff = (uint8_t *)malloc(msg_size + structure_size);
  
    PRINTF("\r\n######################g3api_verify_dynamic######################\r\n");   
  	switch (dauth_option)
	{
	case DYN_AUTH_ECDSA_SHA256:
	case DYN_AUTH_CERT_PUB_ECDSA_SHA256:
		if (structure_size != 64){
			return G3_INVAILD_DATA;
		}
		break;
		break;
	case DYN_AUTH_HMAC:
		if (structure_size != 32){
			return G3_INVAILD_DATA;
		}
		break;
	case DYN_AUTH_SYMM:
		if (structure_size !=16){
			return G3_INVAILD_DATA;
		}
		break;

	default:
		return G3_INVAILD_COMMAND;
	}
   
   	memcpy(pbuff, msg, msg_size);
	memcpy(pbuff + msg_size, sign_structure, structure_size);
                
	ret_code = g3_normal_process(G3_VERIFY,  key_index, MAKEWORD(dauth_option, pos_pub_dynamic), pbuff, msg_size + structure_size,NULL);

    	free(pbuff);
        
        return ret_code;
  
}
/**
  * @brief  Used for session key agreement... 
  *  Parameters (0x87)
  *      en_ecdh_mode                    :  The mode of ECDH instruction It can be one of the following values :   
  *                                         NORMAL_ECDH, GEN_TLS_BLOCK, SET_TLS_SESSION_KEY   
  *      Q_b                             :  The type of public key It can be one of the following values :    
  *                                         ST_ECC_PUBLIC : puk[64] 
  *                                         ST_ECC_PUBLIC_COMPRESS : puk[33] 
  *      Q_b_struct_size                 :The size of public key 
  *      st_ecdh_random                  :ServerHello.random[32] || ClientHello.random[32] 
  *      Q_chip                          : Command outputs, public key chip(dchipG)[64] 
  *      ecdh_value                      :Command outputs. It depends on the ECDH mode and can be one of the following values : 
  *                                         NORMAL_ECDH : pre_master_secret[32] 
  *                                         GEN_TLS_BLOCK : TLS_key_block[128]   
  *                                         SET_TLS_SESSION_KEY : client_write_IV[16] || server_write_IV[16]                      
  *      ecdh_value_struct_size          : The size of ecdh_value
  *  Returns
  *      G3_StatusTypeDef
  */

G3_StatusTypeDef g3api_ecdh(EN_ECDH_MODE en_ecdh_mode,  void* Q_b, uint8_t Q_b_struct_size, uint8_t* st_ecdh_random, uint8_t* Q_chip, void* ecdh_value, uint8_t ecdh_value_struct_size)
{
  G3_StatusTypeDef ret_code;
  uint8_t *buff;
  uint8_t *precvbuff = NULL;
        
     	memcpy(buff, Q_b, Q_b_struct_size);
        
    PRINTF("\r\n######################g3api_ecdh######################\r\n");       
  	switch (en_ecdh_mode)
	{
	case NORMAL_ECDH:
            ret_code = g3_normal_process(G3_ECDH, 0, en_ecdh_mode, buff, Q_b_struct_size, &precvbuff);
            if (ret_code < 0) 
            return ret_code;
        
		break;
	case GEN_TLS_BLOCK:
	case SET_TLS_SESSION_KEY:
            memcpy(buff+Q_b_struct_size, st_ecdh_random, 32);
            ret_code = g3_normal_process(G3_ECDH, 0, en_ecdh_mode, buff,Q_b_struct_size+32, &precvbuff);
            if (ret_code < 0) 
            return ret_code;
        
            break;
	}
  
   	memcpy(Q_chip, precvbuff, 64);
	memcpy(ecdh_value, precvbuff+64, ecdh_value_struct_size);

    	free(precvbuff);
    	free(buff);        
        return ret_code;
  
}


