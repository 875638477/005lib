  uint8_t rx_buffer[240];
  
  uint32_t tx_size = 0;
  
  uint8_t public_key[64];
  
  uint8_t plain_text[1024];
  
  uint8_t C1[64];
  uint8_t C2[1024];
  uint8_t C3[32];

  G3_wakeup();
  
//**********************************  Provisioning  **********************************************************
  
  /* Write setup area sector 5 */
  tx_size = set_buffer_from_hexstr(tx_buffer, "DE54000000000000EE540000000000000E540000000000000054000000000000");
  g3api_write_key_value(0x05, SETUP_AREA, PLAIN_TEXT, tx_buffer, tx_size);
  
  /* write key area sector 4 ( External private key ) */
  tx_size = set_buffer_from_hexstr(tx_buffer, "3945208F7B2144B13F36E38AC6D39F95889393692860B51A42FB81EF4DF7C5B8");
  g3api_write_key_value(0x04, KEY_AREA, PLAIN_TEXT, tx_buffer, 32);   
  
  /* get public key from sector 4 ( Generate the public key from the private key in sector 4 ) */
  g3api_get_public_key(0x04, KEY_SECTOR, public_key, 64);

  /* Write public key(x) key area sector 5 */
  g3api_write_key_value(0x05, KEY_AREA, PLAIN_TEXT, public_key, 32);    

  /* Write public key(y) key area sector 6 */
  g3api_write_key_value(0x06, KEY_AREA, PLAIN_TEXT, public_key + 32, 32);  

//***********************************  ENCRPYT 512 byte ****************************************************************
 
  /* Encrpyt Init - SM2encrpyt initialize */
  g3api_encryption(0x05, SECTOR_KEY, BL_SM2_INIT, NULL, NULL, 0x00, C1);
      
  /* Encrypt update - SM2encrypt update */
  // Set plain text
  set_buffer_from_hexstr(plain_text, "A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0A0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0B0C0C0C0C0C0C0C0C0C0C0C0C0C0C0C0C0C0C0C0C0C0C0C0C0C0C0C0C0C0C0C0C0");
  
