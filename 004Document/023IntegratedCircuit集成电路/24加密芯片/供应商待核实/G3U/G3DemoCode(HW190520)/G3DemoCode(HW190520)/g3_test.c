  memcpy( C2 + 240, rx_buffer, 240 );
  
  g3api_encryption(0x05, SECTOR_KEY, BL_SM2_UPDATE, NULL, plain_text + 240 + 240, 32, rx_buffer);
  memcpy( C2 + 240 + 240, rx_buffer, 240 );
  
  /* Encrypt final - SM2encrpyt final */
  g3api_encryption(0x05, SECTOR_KEY, BL_SM2_FINAL, NULL, NULL, 0x00, C3);
 
  
//***********************************  DECRPYT 512 byte ****************************************************************

  /* Decrypt Init - SM2decrypt initialize */
  g3api_decryption(0x04, SECTOR_KEY, BL_SM2_INIT, NULL, C1, sizeof(C1), rx_buffer);
  
  /* Decrypt update - SM2decrypt update */
  g3api_decryption(0x04, SECTOR_KEY, BL_SM2_UPDATE, NULL, C2, 240, rx_buffer);
  
  if( memcmp(plain_text, rx_buffer, 240) != 0 )
    printf("SM2decypt update failed! \r\n");

