param(
    [string]$CadencePcbEnv = '',
    [switch]$Lga1700
)
$ErrorActionPreference='Stop'
$libraryRoot=(Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '..')).Path.Replace('\','/')
foreach($name in @('01env','01Pad_lib','01Psm_lib','01script_file','01_3d_step_lib')){
    if(-not(Test-Path -LiteralPath (Join-Path $libraryRoot $name) -PathType Container)){throw "Missing library directory: $name"}
}
if(-not $CadencePcbEnv){
    $cadenceHome=if($env:HOME){$env:HOME}else{$env:USERPROFILE}
    $CadencePcbEnv=Join-Path $cadenceHome 'pcbenv'
}
$source=Join-Path $libraryRoot '01env/env'
$config=[IO.File]::ReadAllText($source,[Text.Encoding]::UTF8)
$config=$config.Replace('D:\001DIY\005lib',$libraryRoot.Replace('/','\')).Replace('D:/001DIY/005lib',$libraryRoot)
$config=$config.Replace('D:\005lib',$libraryRoot.Replace('/','\')).Replace('D:/005lib',$libraryRoot)
$extra="`n# Local paths generated by setup_library_paths.ps1`n"
$psmFolders=@("`"$libraryRoot/01Psm_lib`"")
if($Lga1700){
    foreach($folder in @('LGA1700_MOD26_20261106','LGA1700_MOD31_3D_20261108')){
        if(-not(Test-Path -LiteralPath "$libraryRoot/01Psm_lib/$folder")){throw "Missing LGA1700 variant: $folder"}
    }
    $psmFolders=@("`"$libraryRoot/01Psm_lib/LGA1700_MOD26_20261106`"","`"$libraryRoot/01Psm_lib/LGA1700_MOD31_3D_20261108`"","`"$libraryRoot/01Psm_lib`"")
}
$extra+='set psmpath = ( '+($psmFolders -join ' ')+' )'+"`n"
$extra+="set padpath = ( `"$libraryRoot/01Pad_lib`" )`nset steppath = ( `"$libraryRoot/01_3d_step_lib`" )`nset step_mapping_path = ( `"$libraryRoot/01_3d_step_lib`" )`nset scriptpath = ( `".`" `"$libraryRoot/01script_file`" )`n"
New-Item -ItemType Directory -Path $CadencePcbEnv -Force | Out-Null
$destination=Join-Path $CadencePcbEnv 'env'
if(Test-Path -LiteralPath $destination){Copy-Item -LiteralPath $destination -Destination ($destination+'.before_'+(Get-Date -Format 'yyyyMMdd_HHmmss'))}
[IO.File]::WriteAllText($destination,$config+$extra,(New-Object Text.UTF8Encoding($false)))
Write-Output "Installed library paths: $destination"
Write-Output "Library root: $libraryRoot; LGA1700 variants: $Lga1700"
